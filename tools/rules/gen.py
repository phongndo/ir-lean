"""The rules' source files, and the Lean statements generated from them.

`statements_text` is the first of the two generators docs/rules.md describes: every rule's proposition, as
rules/Rules/Statements.lean, which is checked in and has to be what this prints. The second, the matcher, is
`lang.Rule.match` and `lang.Rule.build`.
"""

from __future__ import annotations

import sys
from pathlib import Path

import lang

ROOT = Path(__file__).resolve().parent.parent.parent
sys.path.append(str(ROOT / "tools"))

from irlean import schemas  # noqa: E402

SOURCES = ROOT / "rules" / "src"
STATEMENTS = ROOT / "rules" / "Rules" / "Statements.lean"

HEADER = """import IRLean.Int
import IRLean.Refine

/-! # Each rule's statement

Generated by `tools/rules/rules.py gen` from `rules/src/*.json`. Do not edit: `rules.py gen --check` fails if
this isn't what the source generates. docs/rules.md says what a statement claims.

Each says a replacement refines a pattern, `IRLean.Refines`, for every width, every operand, poison included,
every flag the pattern leaves open, and every constant meeting the rule's side conditions. A rule is proved
when `Rules.<name>` is a theorem of `Rules.Stmt.<name>` on the standard three axioms. -/

namespace Rules.Stmt

open IRLean
"""


def load_all(directory: Path = SOURCES) -> list[lang.Rule]:
    """Every rule, file by file in name order, each file's in its own order."""
    rules: list[lang.Rule] = []
    for path in sorted(directory.glob("*.json")):
        try:
            rules += lang.load(schemas.read(path, schemas.RULES))
        except (lang.RuleError, schemas.SchemaError) as error:
            raise lang.RuleError(f"{path.name}: {error}") from error
    names = [r.name for r in rules]
    twice = sorted({n for n in names if names.count(n) > 1})
    if twice:
        raise lang.RuleError(f"rules named in two files: {', '.join(twice)}")
    return rules


def describe(rule: lang.Rule) -> str:
    """A rule in one line, as its docstring has it."""
    text = f"`{rule.name}`: `{lang.show(rule.pattern)}` to `{lang.show(rule.replacement)}`"
    if rule.conds:
        text += ", where " + " and ".join(f"`{lang.show(c)}`" for c in rule.conds)
    return text + "."


def statements_text(rules: list[lang.Rule]) -> str:
    out = [HEADER]
    for rule in rules:
        out.append(f"\n/-- {describe(rule)} -/\n@[reducible] def {rule.name} : Prop :=\n{rule.statement()}\n")
    out.append("\nend Rules.Stmt\n")
    return "".join(out)
